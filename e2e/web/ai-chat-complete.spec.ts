/**
 * Stubs `POST .../ai/chat/stream` with a terminal text reply and records the
 * request body, so the test can assert exactly what the UI put on the wire.
 */
async function stubStream(page: Page): Promise<{ bodies: Record<string, unknown>[] }> {
  const bodies: Record<string, unknown>[] = [];
  await page.route("**/ai/chat/stream", async (route: Route) => {
    const request = route.request();
    try {
      bodies.push(request.postDataJSON() as Record<string, unknown>);
    } catch {
      bodies.push({});
    }
    await route.fulfill({
      status: 200,
      headers: {
        "content-type": "text/event-stream; charset=utf-8",
        "cache-control": "no-store",
      },
      body: sse([
        ["meta", META],
        ["text.delta", { type: "text.delta", delta: "这是一条用于验收的回复。" }],
        ["done", { type: "done", messageId: "stub-assistant-message", finishReason: "stop" }],
      ]),
    });
  });
  return { bodies };
}

async function latestConversation(
  page: Page,
): Promise<{ id: string; title: string; workspaceId: string }> {
  const workspaces = (await (
    await page.request.get(`${WEB_URL}/v1/me/workspaces`)
  ).json()) as Array<{ id: string; slug: string }>;
  const workspace = workspaces.find((entry) => entry.slug === WORKSPACE_SLUG);
  expect(workspace, `workspace ${WORKSPACE_SLUG} must exist`).toBeTruthy();

  for (let attempt = 0; attempt < 30; attempt += 1) {
    const response = await page.request.get(
      `${WEB_URL}/v1/workspaces/${workspace?.id}/ai/conversations?limit=1`,
    );
    if (response.status() === 200) {
      const body = (await response.json()) as {
        items: Array<{ id?: string; title?: string | null; lastMessageAt?: string | null }>;
      };
      // The list is ordered `lastMessageAt` desc, so index 0 *is* this turn's
      // conversation. A title is not required: title generation is an AI call and
      // may legitimately fail (`AI_UPSTREAM`) without affecting the message.
      const item = body.items[0];
      if (item?.id) {
        return { id: item.id, title: item.title?.trim() ?? "", workspaceId: workspace!.id };
      }
    }
    await page.waitForTimeout(2_000);
  }
  throw new Error("no AI conversation was found after sending");
}

