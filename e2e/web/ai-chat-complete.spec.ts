/** SSE frame body the web transport accepts (id / event / data, blank line). */
function sse(frames: [string, unknown][]): string {
  return frames
    .map(([event, data], index) => `id: ${index + 1}\nevent: ${event}\ndata: ${JSON.stringify(data)}\n\n`)
    .join("");
}

