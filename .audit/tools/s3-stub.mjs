/**
 * Local S3-compatible object store for the dev stack.
 *
 * The production deployment runs MinIO (docker/compose.production.yml:85); the
 * Windows dev host has neither Docker nor a MinIO binary, and without an
 * endpoint every browser PUT to a presigned URL fails with
 * ERR_CONNECTION_REFUSED — which the assistant-ui attachment pipeline then
 * treats as "upload failed" and returns the message to the draft.
 *
 * This is not a product component. It answers the subset of S3 the app uses:
 * bucket creation, PutObject (browser-direct, presigned, query string ignored),
 * GetObject/HeadObject for reads and the presigned probe, and DeleteObject.
 * Signatures are not verified: the presigned URL is still generated by the real
 * `@aws-sdk/client-s3` signer through the API, this only provides the endpoint
 * it points at.
 *
 * Usage: node .audit/tools/s3-stub.mjs [port]
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { createServer } from "node:http";
import { dirname, join, resolve } from "node:path";

const PORT = Number(process.argv[2] ?? process.env.S3_STUB_PORT ?? 9000);
const ROOT = resolve(process.cwd(), ".data/s3-stub");

function keyPath(bucket, key) {
  // Keep each object on disk so a refresh after upload still serves the bytes.
  const safeBucket = bucket.replaceAll(/[^a-zA-Z0-9._-]/gu, "_");
  const safeKey = key.replaceAll(/[^a-zA-Z0-9._\u4e00-\u9fff/-]/gu, "_");
  return join(ROOT, safeBucket, safeKey);
}

function xml(body) {
  return `<?xml version="1.0" encoding="UTF-8"?>\n${body}`;
}

function notFound(res, code = "NoSuchKey") {
  res.writeHead(404, { "content-type": "application/xml" });
  res.end(xml(`<Error><Code>${code}</Code><Message>Not Found</Message></Error>`));
}

async function readBody(req) {
  const chunks = [];
  for await (const chunk of req) chunks.push(chunk);
  return Buffer.concat(chunks);
}

const server = createServer(async (req, res) => {
  const url = new URL(req.url ?? "/", `http://${req.headers.host ?? "localhost"}`);
  // `pathname` arrives as /<bucket>/<key…>; the key keeps its slashes.
  const segments = url.pathname.replace(/^\/+/u, "").split("/");
  const bucket = decodeURIComponent(segments.shift() ?? "");
  const key = segments.map((segment) => decodeURIComponent(segment)).join("/");

  // Log every request shape. When the API wraps a storage call in a 500 this
  // line is what says whether the stub was asked for something it does not
  // implement (a multipart or list query, a variant key it never wrote).
  if (process.env.S3_STUB_VERBOSE !== "0") {
    console.log(
      `[s3-stub] ${req.method} /${bucket}/${key}${url.search ? ` (query: ${url.search.slice(1, 80)})` : ""}`,
    );
  }

  res.setHeader("access-control-allow-origin", "*");
  res.setHeader("access-control-allow-methods", "GET,PUT,HEAD,DELETE,POST,OPTIONS");
  res.setHeader(
    "access-control-allow-headers",
    req.headers["access-control-request-headers"] ?? "*",
  );
  res.setHeader("access-control-expose-headers", "ETag,Content-Length,Content-Type");

  if (req.method === "OPTIONS") {
    res.writeHead(204);
    res.end();
    return;
  }

  try {
    // ListBuckets — the storage probe asks for it on first load.
    if (!bucket) {
      res.writeHead(200, { "content-type": "application/xml" });
      res.end(xml("<ListAllMyBucketsResult><Buckets></Buckets></ListAllMyBucketsResult>"));
      return;
    }

    // Bucket-level: create / delete.
    if (!key) {
      if (req.method === "PUT") {
        await mkdir(join(ROOT, bucket), { recursive: true });
        res.writeHead(200);
        res.end();
        return;
      }
      if (req.method === "DELETE") {
        await rm(join(ROOT, bucket), { recursive: true, force: true });
        res.writeHead(204);
        res.end();
        return;
      }
      if (req.method === "HEAD") {
        res.writeHead(200);
        res.end();
        return;
      }
      res.writeHead(200, { "content-type": "application/xml" });
      res.end(xml("<ListBucketResult><Contents></Contents></ListBucketResult>"));
      return;
    }

    const path = keyPath(bucket, key);

    if (req.method === "PUT") {
      const body = await readBody(req);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, body);
      // Remember the upload's Content-Type. The API re-reads the object on
      // `complete` and rejects it as MEDIA_UNSUPPORTED_TYPE if the store hands
      // back `application/octet-stream`, so serving a fixed type is not enough.
      await writeFile(
        `${path}.meta.json`,
        JSON.stringify({ contentType: req.headers["content-type"] ?? "application/octet-stream" }),
      );
      const etag = `"${createHash("md5").update(body).digest("hex")}"`;
      // No `content-length` on the PUT reply: S3 answers `200` with an empty
      // body. Declaring the request's length made the browser abort the upload
      // with `ERR_CONTENT_LENGTH_MISMATCH` (response promised 51 bytes, sent 0).
      res.writeHead(200, { etag });
      res.end();
      return;
    }

    if (req.method === "GET" || req.method === "HEAD") {
      try {
        const info = await stat(path);
        const bytes = req.method === "GET" ? await readFile(path) : undefined;
        let contentType = "application/octet-stream";
        try {
          contentType = JSON.parse(await readFile(`${path}.meta.json`, "utf8")).contentType;
        } catch {
          // Objects written before the sidecar existed, or by a test, keep the
          // generic type.
        }
        res.writeHead(200, {
          "content-type": contentType,
          "content-length": String(info.size),
          etag: `"${createHash("md5").update(bytes ?? Buffer.alloc(0)).digest("hex")}"`,
          "cache-control": "no-store",
        });
        res.end(bytes);
      } catch {
        notFound(res);
      }
      return;
    }

    if (req.method === "DELETE") {
      await rm(path, { force: true });
      res.writeHead(204);
      res.end();
      return;
    }

    res.writeHead(405);
    res.end();
  } catch (error) {
    console.error("[s3-stub]", req.method, url.pathname, error);
    res.writeHead(500, { "content-type": "application/xml" });
    res.end(xml("<Error><Code>InternalError</Code></Error>"));
  }
});

await mkdir(ROOT, { recursive: true });
server.listen(PORT, "127.0.0.1", () => {
  console.log(`[s3-stub] listening on http://127.0.0.1:${PORT} (root ${ROOT})`);
});