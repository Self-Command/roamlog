export function registerSchemas(registry: OpenAPIRegistry): void {
  for (const [name, schema] of Object.entries(schemas)) {
    const registered = registry.register(name, schema);
    if (!registeredSchemas.has(schema)) {
      registeredSchemas.set(schema, registered);
    }
  }
}

export function resolveRegisteredSchema<T>(schema: T): T {
  if (typeof schema !== "object" || schema === null) {
    return schema;
  }
  return (registeredSchemas.get(schema) as T | undefined) ?? schema;
}
