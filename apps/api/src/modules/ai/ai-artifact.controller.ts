import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  HttpStatus,
  Inject,
  Param,
  Patch,
  Post,
  Query,
  UseGuards,
} from "@nestjs/common";
import {
  AiArtifactListQuerySchema,
  CreateAiArtifactRequestSchema,
  SetAiArtifactSuggestionRequestSchema,
  UpdateAiArtifactRequestSchema,
  UuidV7Schema,
} from "@roamlog/contracts";

import {
  CurrentActor,
  CurrentWorkspaceMembership,
  type AuthenticatedActor,
} from "../../common/guards/actor-context.js";
import { RequirePermission } from "../../common/guards/require-permission.decorator.js";
import { RolesGuard } from "../../common/guards/roles.guard.js";
import { TenantGuard } from "../../common/guards/tenant.guard.js";
import { parseRequest } from "../../common/services/request-validation.js";
import type { WorkspaceMembershipAccess } from "../../common/services/workspace-access.service.js";
import {
  AiArtifactService,
  AiArtifactVersionParamSchema,
} from "./ai-artifact.service.js";

/**
 * Workspace-scoped artifact REST surface. The actions deliberately mirror the
 * AI chat permission (`trip:create`), because artifacts are generated by the
 * same assistant and are scoped to the same workspace.
 */
@Controller("workspaces/:workspaceId/ai/artifacts")
@UseGuards(TenantGuard, RolesGuard)
export class AiArtifactController {
  constructor(@Inject(AiArtifactService) private readonly artifacts: AiArtifactService) {}

  @Get()
  @RequirePermission("trip:create", "trip")
  list(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Query() query: unknown,
  ) {
    return this.artifacts.list(
      actor,
      membership,
      parseRequest(AiArtifactListQuerySchema, query),
    );
  }

  @Post()
  @RequirePermission("trip:create", "trip")
  create(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Body() body: unknown,
  ) {
    return this.artifacts.create(
      actor,
      membership,
      parseRequest(CreateAiArtifactRequestSchema, body),
    );
  }

  @Get(":artifactId")
  @RequirePermission("trip:create", "trip")
  fetch(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Param("artifactId") artifactId: string,
  ) {
    return this.artifacts.fetch(
      actor,
      membership,
      parseRequest(UuidV7Schema, artifactId),
    );
  }

  @Patch(":artifactId")
  @RequirePermission("trip:create", "trip")
  update(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Param("artifactId") artifactId: string,
    @Body() body: unknown,
  ) {
    return this.artifacts.update(
      actor,
      membership,
      parseRequest(UuidV7Schema, artifactId),
      parseRequest(UpdateAiArtifactRequestSchema, body),
    );
  }

  @Delete(":artifactId")
  @RequirePermission("trip:create", "trip")
  remove(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Param("artifactId") artifactId: string,
  ) {
    return this.artifacts.remove(
      actor,
      membership,
      parseRequest(UuidV7Schema, artifactId),
    );
  }

  @Get(":artifactId/versions")
  @RequirePermission("trip:create", "trip")
  versions(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Param("artifactId") artifactId: string,
  ) {
    return this.artifacts.versions(
      actor,
      membership,
      parseRequest(UuidV7Schema, artifactId),
    );
  }

  @Post(":artifactId/versions/:version/restore")
  @HttpCode(HttpStatus.OK)
  @RequirePermission("trip:create", "trip")
  restore(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Param("artifactId") artifactId: string,
    @Param("version") version: string,
  ) {
    return this.artifacts.restoreVersion(
      actor,
      membership,
      parseRequest(UuidV7Schema, artifactId),
      parseRequest(AiArtifactVersionParamSchema, version),
    );
  }

  @Get(":artifactId/suggestions")
  @RequirePermission("trip:create", "trip")
  suggestions(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Param("artifactId") artifactId: string,
  ) {
    return this.artifacts.suggestions(
      actor,
      membership,
      parseRequest(UuidV7Schema, artifactId),
    );
  }

  @Patch(":artifactId/suggestions/:suggestionId")
  @RequirePermission("trip:create", "trip")
  resolveSuggestion(
    @CurrentActor() actor: AuthenticatedActor,
    @CurrentWorkspaceMembership() membership: WorkspaceMembershipAccess,
    @Param("artifactId") artifactId: string,
    @Param("suggestionId") suggestionId: string,
    @Body() body: unknown,
  ) {
    const input = parseRequest(SetAiArtifactSuggestionRequestSchema, body);
    return this.artifacts.resolveSuggestion(
      actor,
      membership,
      parseRequest(UuidV7Schema, artifactId),
      parseRequest(UuidV7Schema, suggestionId),
      input.isResolved,
    );
  }
}
